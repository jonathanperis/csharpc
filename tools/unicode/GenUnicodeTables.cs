        /// <summary>{{lowerRuns}} ToLowerInvariant runs: (start, end, stride, delta mod 2^16).</summary>
        internal const int LowerRunCount = {{lowerRuns}};
        internal static ReadOnlySpan<byte> LowerRuns => """{{lower}}"""u8;
    }
