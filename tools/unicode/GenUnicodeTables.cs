{
    internal static class UnicodeData
    {
        /// <summary>{{count}} (start, UnicodeCategory) breakpoints covering U+0000..U+FFFF.</summary>
        internal const int CategoryCount = {{count}};
        internal static ReadOnlySpan<byte> Categories => """{{categories}}"""u8;

        /// <summary>UnicodeCategory of U+0000..U+00FF, one symbol each.</summary>
        internal static ReadOnlySpan<byte> Latin1Categories => """{{latin1}}"""u8;

        /// <summary>Chars below this use the dense case-delta tables; others the runs.</summary>
        internal const int DenseCaseLimit = {{DenseLimit}};
        internal static ReadOnlySpan<byte> UpperDense => """{{upperDense}}"""u8;
        internal static ReadOnlySpan<byte> LowerDense => """{{lowerDense}}"""u8;

        /// <summary>{{upperRuns}} ToUpperInvariant runs: (start, end, stride, delta mod 2^16).</summary>
        internal const int UpperRunCount = {{upperRuns}};
