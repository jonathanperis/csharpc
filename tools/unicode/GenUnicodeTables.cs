// Generates src/Csharpc/corelib/UnicodeData.g.cs from the running .NET's own Unicode data, so
// csharpc's System.Char behaves exactly like .NET's (invariant culture).
//
//   dotnet run tools/unicode/GenUnicodeTables.cs -- src/Csharpc/corelib/UnicodeData.g.cs
//
// Tables are stored as printable text in UTF-8 literals (constant data in the binary, no static
// arrays to initialize): every 16-bit number is 3 characters of a 64-symbol alphabet ('0'..'o').
using System.Globalization;
using System.Text;

var output = args.Length > 0 ? args[0] : "UnicodeData.g.cs";

string Enc(int v) => new string([(char)('0' + ((v >> 12) & 63)), (char)('0' + ((v >> 6) & 63)), (char)('0' + (v & 63))]);

// 1. General category breakpoints: (start, category) whenever the category changes.
var categories = new StringBuilder();
int count = 0;
int previous = -1;
for (int c = 0; c <= 0xFFFF; c++)
{
    int cat = (int)char.GetUnicodeCategory((char)c);
    if (cat == previous) continue;
    categories.Append(Enc(c)).Append(Enc(cat));
    previous = cat;
    count++;
}

// 2. Case mapping runs: every mapped char, merged into runs of consecutive chars with equal delta
//    (stride 1) or alternating upper/lower pairs (stride 2).
string Runs(Func<char, char> map, out int runs)
{
    var points = new List<(int C, int Delta)>();
    for (int c = 0; c <= 0xFFFF; c++) { int d = map((char)c) - c; if (d != 0) points.Add((c, d)); }
    var sb = new StringBuilder();
    runs = 0;
    var used = new bool[points.Count];
    var index = points.Select((p, i) => (p.C, i)).ToDictionary(x => x.C, x => x.i);
    for (int i = 0; i < points.Count; i++)
    {
        if (used[i]) continue;
        var (start, delta) = points[i];
        int stride = index.TryGetValue(start + 1, out var n1) && !used[n1] && points[n1].Delta == delta ? 1 : 2;
        int end = start;
        used[i] = true;
        while (index.TryGetValue(end + stride, out var j) && !used[j] && points[j].Delta == delta) { end += stride; used[j] = true; }
        sb.Append(Enc(start)).Append(Enc(end)).Append(Enc(stride)).Append(Enc(delta & 0xFFFF));
        runs++;
    }
    return sb.ToString();
}

var upper = Runs(char.ToUpperInvariant, out int upperRuns);
var lower = Runs(char.ToLowerInvariant, out int lowerRuns);

// 3. Dense case deltas for U+0000..U+024F (Latin-1 + Latin Extended-A/B), the common case.
const int DenseLimit = 0x250;
var upperDense = new StringBuilder();
var lowerDense = new StringBuilder();
for (int c = 0; c < DenseLimit; c++)
{
    upperDense.Append(Enc((char.ToUpperInvariant((char)c) - c) & 0xFFFF));
    lowerDense.Append(Enc((char.ToLowerInvariant((char)c) - c) & 0xFFFF));
}

// 4. Latin-1 fast path: category per char (one symbol each).
var latin1 = new StringBuilder();
for (int c = 0; c < 256; c++) latin1.Append((char)('0' + (int)char.GetUnicodeCategory((char)c)));

var file = $$""""
// <auto-generated>
// Generated by tools/unicode/GenUnicodeTables.cs from .NET {{Environment.Version}} — do not edit by hand.
// Every 16-bit number is 3 characters of the alphabet '0'..'o' (6 bits each).
// </auto-generated>
#nullable disable
