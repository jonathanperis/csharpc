// Generates src/Csharpc/corelib/Globalization/GraphemeData.g.cs: the grapheme cluster break property of
// every code point (UAX #29's Grapheme_Cluster_Break plus Extended_Pictographic, .NET's
// GraphemeClusterBreakType), read from the running .NET's own data (CharUnicodeInfo.GetGraphemeClusterBreakType,
// internal), for StringInfo's text elements.
//
//   dotnet run tools/unicode/GenGraphemeTable.cs -- src/Csharpc/corelib/Globalization/GraphemeData.g.cs
//
// The table is (start, type) breakpoints over U+0000..U+10FFFF, each start << 4 | type written as 5
// characters of a 64-symbol alphabet ('0'..'o') in a UTF-8 literal.
using System.Globalization;
using System.Reflection;
using System.Text;

var output = args.Length > 0 ? args[0] : "GraphemeData.g.cs";
var get = typeof(CharUnicodeInfo).GetMethod("GetGraphemeClusterBreakType", BindingFlags.NonPublic | BindingFlags.Static, [typeof(Rune)])
    ?? throw new InvalidOperationException("CharUnicodeInfo.GetGraphemeClusterBreakType(Rune) not found");

var table = new StringBuilder();
int count = 0, previous = -1;
for (int cp = 0; cp <= 0x10FFFF; cp++)
{
    // Surrogate code points aren't scalars: they decode to U+FFFD (Other) anyway.
    int type = cp is >= 0xD800 and <= 0xDFFF ? 0 : Convert.ToInt32(get.Invoke(null, [new Rune(cp)]));
    if (type is < 0 or > 15) throw new InvalidOperationException($"type {type}");
    if (type == previous) continue;
    int packed = (cp << 4) | type;
    foreach (var shift in new[] { 24, 18, 12, 6, 0 }) table.Append((char)('0' + ((packed >> shift) & 63)));
    previous = type;
    count++;
}

var version = typeof(object).Assembly.GetName().Version!;
File.WriteAllText(output, $$""""
    // <auto-generated>
    // Generated by tools/unicode/GenGraphemeTable.cs from .NET {{version.Major}}.{{version.Minor}}.{{version.Build}} — do not edit by hand.
    // </auto-generated>
    #nullable disable
    using System;

    namespace CsharpcCoreLib.Globalization
    {
        internal static class GraphemeData
        {
            /// <summary>{{count}} (start, GraphemeClusterBreakType) breakpoints over U+0000..U+10FFFF: start &lt;&lt; 4 | type, 5 symbols each.</summary>
            internal const int Count = {{count}};
            internal static ReadOnlySpan<byte> Breakpoints => """{{table}}"""u8;
        }
    }

    """");
Console.WriteLine($"{count} breakpoints -> {output}");
