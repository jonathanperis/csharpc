// Generates src/Csharpc/corelib/Globalization/BidiData.g.cs from the running .NET's own bidi data
// (CharUnicodeInfo.GetBidiCategoryNoBoundsChecks, internal: read through reflection), for IdnMapping's bidi rule in
// invariant globalization mode.
//
//   dotnet run tools/unicode/GenBidiTable.cs -- src/Csharpc/corelib/Globalization/BidiData.g.cs
//
// The table is the code points where the strong bidi category changes (Other, StrongLeftToRight,
// StrongRightToLeft), each 4 characters of a 64-symbol alphabet ('0'..'o'): start << 2 | category.
using System.Globalization;
using System.Reflection;
using System.Text;

var output = args.Length > 0 ? args[0] : "BidiData.g.cs";
var method = typeof(CharUnicodeInfo).GetMethod("GetBidiCategoryNoBoundsChecks", BindingFlags.Static | BindingFlags.NonPublic, [typeof(uint)])
    ?? throw new InvalidOperationException("CharUnicodeInfo.GetBidiCategoryNoBoundsChecks(uint) not found");

int Category(int codePoint)
{
    var value = Convert.ToInt32(method.Invoke(null, [(uint)codePoint]));
    return value switch { 0 => 0, 0x20 => 1, 0x40 => 2, _ => throw new InvalidOperationException($"bidi category {value:X}") };
}

string Enc(int v) => new string([(char)('0' + ((v >> 18) & 63)), (char)('0' + ((v >> 12) & 63)), (char)('0' + ((v >> 6) & 63)), (char)('0' + (v & 63))]);

var table = new StringBuilder();
int count = 0, previous = -1;
for (int c = 0; c <= 0x10FFFF; c++)
{
    int cat = Category(c);
    if (cat == previous) continue;
    table.Append(Enc((c << 2) | cat));
    previous = cat;
    count++;
}

File.WriteAllText(output, $$""""
// <auto-generated>
// Generated by tools/unicode/GenBidiTable.cs from .NET {{Environment.Version}} — do not edit by hand.
// </auto-generated>
#nullable disable
using System;

namespace CsharpcCoreLib.Globalization
{
    internal static partial class BidiData
    {
        /// <summary>{{count}} breakpoints over U+0000..U+10FFFF: start &lt;&lt; 2 | category (0 other, 1 L, 2 R/AL), 4 characters each.</summary>
        internal const int Count = {{count}};
        internal static ReadOnlySpan<byte> Breakpoints => """{{table}}"""u8;
    }
}

"""");
Console.WriteLine($"{count} breakpoints");
