// Generates src/Csharpc/corelib/Globalization/IdnBidi.g.cs: the strong bidirectional category of every
// code point (StrongLeftToRight, StrongRightToLeft, Other), read from the running .NET's own data
// (CharUnicodeInfo.GetBidiCategoryNoBoundsChecks, internal), which IdnMapping's invariant-mode Punycode checks use.
//
//   dotnet run tools/unicode/GenBidiTable.cs -- src/Csharpc/corelib/Globalization/IdnBidi.g.cs
//
// The table is (start, category) breakpoints over U+0000..U+10FFFF, each start << 2 | category written as
// 4 characters of a 64-symbol alphabet ('0'..'o') in a UTF-8 literal (constant data, nothing to initialize).
using System.Globalization;
using System.Reflection;
using System.Text;

var output = args.Length > 0 ? args[0] : "IdnBidi.g.cs";
var getBidi = typeof(CharUnicodeInfo).GetMethod("GetBidiCategoryNoBoundsChecks", BindingFlags.NonPublic | BindingFlags.Static, [typeof(uint)])
    ?? throw new InvalidOperationException("CharUnicodeInfo.GetBidiCategoryNoBoundsChecks(uint) not found");
int Category(int cp)
{
    return Convert.ToInt32(getBidi.Invoke(null, [(uint)cp])) switch { 0x20 => 1, 0x40 => 2, 0 => 0, var v => throw new InvalidOperationException($"bidi value {v}") };
}

var table = new StringBuilder();
int count = 0, previous = -1;
for (int cp = 0; cp <= 0x10FFFF; cp++)
{
    int category = Category(cp);
    if (category == previous) continue;
    int packed = (cp << 2) | category;
    foreach (var shift in new[] { 18, 12, 6, 0 }) table.Append((char)('0' + ((packed >> shift) & 63)));
    previous = category;
    count++;
}

var version = typeof(object).Assembly.GetName().Version!;
File.WriteAllText(output, $$""""
    // <auto-generated>
    // Generated by tools/unicode/GenBidiTable.cs from .NET {{version.Major}}.{{version.Minor}}.{{version.Build}} — do not edit by hand.
    // </auto-generated>
    #nullable disable
    using System;

    namespace CsharpcCoreLib.Globalization
    {
        internal static class IdnBidiData
        {
            /// <summary>{{count}} (start, category) breakpoints over U+0000..U+10FFFF: start &lt;&lt; 2 | category (0 other, 1 L, 2 R/AL), 4 symbols each.</summary>
            internal const int Count = {{count}};
            internal static ReadOnlySpan<byte> Breakpoints => """{{table}}"""u8;
        }
    }

    """");
Console.WriteLine($"{count} breakpoints -> {output}");
