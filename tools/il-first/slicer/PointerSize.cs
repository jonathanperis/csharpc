using Mono.Cecil;
using Mono.Cecil.Cil;

/// <summary>
/// The exact pointer-size check (#382): every member a slice copies, compared between the 64-bit CoreLib it was cut from and the 32-bit
/// CoreLib of the same version. CoreLib is compiled per target, so a member compiled under <c>TARGET_64BIT</c> (or with <c>IntPtr.Size</c> folded
/// by the trimmer) has different IL there: field types and offsets, <c>[InlineArray]</c> lengths, class size, RVA data, method bodies. Those are
/// the members a 32-bit target must never run from the 64-bit slice; the build cuts wasm32's slice from the 32-bit CoreLib for that reason, and
/// this report lists them. It also fails when the two slices do not serve the same types, which would leave a 32-bit target without one.
/// </summary>
static class PointerSize
{
    const string Prefix = "CsharpcCoreLib.Upstream.";

    public static int Run(string slice64, string slice32, string coreLib64, string coreLib32, string report)
    {
        var real64 = MapKeys(Path.ChangeExtension(slice64, ".map"));
        var real32 = MapKeys(Path.ChangeExtension(slice32, ".map"));
        if (!real64.SetEquals(real32))
        {
            Console.Error.WriteLine("slicer: the 64-bit and the 32-bit slices serve different types: "
                + string.Join(", ", real64.Except(real32).Select(t => "+" + t).Concat(real32.Except(real64).Select(t => "-" + t))));
            return 1;
        }
        var findings = Diff(ModuleDefinition.ReadModule(slice64), ModuleDefinition.ReadModule(coreLib64), ModuleDefinition.ReadModule(coreLib32), out var types, out var methods);
        using (var w = new StreamWriter(report))
        {
            w.WriteLine("# Pointer-size-dependent members of the CoreLib slice");
            w.WriteLine();
            w.WriteLine($"Generated by `tools/il-first/slicer pointer-size` at build time: {types} types and {methods} methods copied by the 64-bit slice, compared");
            w.WriteLine("with the 32-bit CoreLib of the same version. Each member listed was compiled differently for 32-bit targets; wasm32 runs the 32-bit slice.");
            w.WriteLine();
            foreach (var g in findings.GroupBy(f => f.Kind).OrderBy(g => g.Key))
            {
                w.WriteLine($"## {g.Key} ({g.Count()})");
                w.WriteLine();
                foreach (var f in g.OrderBy(f => f.Where, StringComparer.Ordinal)) w.WriteLine($"- `{f.Where}`{(f.Detail.Length > 0 ? ": " + f.Detail : "")}");
                w.WriteLine();
            }
        }
        Console.WriteLine($"slicer: {findings.Select(f => f.Where).Distinct().Count()} pointer-size-dependent members of {methods} methods in {types} types ({report}); "
            + "wasm32 uses the slice cut from the 32-bit CoreLib");
        return 0;
    }

    static HashSet<string> MapKeys(string map) =>
        File.ReadAllLines(map).Where(l => l.IndexOf('=') > 0).Select(l => l[..l.IndexOf('=')]).ToHashSet(StringComparer.Ordinal);

    static IEnumerable<TypeDefinition> All(IEnumerable<TypeDefinition> ts) => ts.SelectMany(t => All(t.NestedTypes).Prepend(t));

    /// <summary>The CoreLib name of a slice type ("CsharpcCoreLib.Upstream.System.Number/BigInteger" -> "System.Number/BigInteger").</summary>
    static string Original(TypeDefinition t)
    {
        var parts = new List<string>();
        var outer = t;
        while (outer.DeclaringType is not null) { parts.Insert(0, outer.Name); outer = outer.DeclaringType; }
        var top = outer.FullName.StartsWith(Prefix, StringComparison.Ordinal) ? outer.FullName[Prefix.Length..] : outer.FullName;
        return parts.Count == 0 ? top : top + "/" + string.Join("/", parts);
    }

    static string Signature(MethodReference m) =>
        m.ReturnType.FullName + " " + m.Name + "(" + string.Join(",", m.Parameters.Select(p => p.ParameterType.FullName)) + ")`" + m.GenericParameters.Count;

    // Branch targets are left out (offsets move when an earlier instruction differs); the instruction sequence still differs then.
    static List<string> Body(MethodDefinition m) => m.HasBody
        ? m.Body.Instructions.Select(i => i.OpCode.Name + " " + i.Operand switch
        {
            null or Instruction => "",
            Instruction[] targets => "switch" + targets.Length,
            MemberReference r => r.FullName,
            VariableDefinition v => "V" + v.Index + ":" + v.VariableType.FullName,
            ParameterDefinition p => "A" + p.Index,
            var o => o.ToString()
        }).ToList()
        : [];

    static string InlineLength(TypeDefinition t) =>
        t.CustomAttributes.FirstOrDefault(a => a.AttributeType.Name == "InlineArrayAttribute")?.ConstructorArguments[0].Value?.ToString() ?? "";

    public record Finding(string Kind, string Where, string Detail);

    public static List<Finding> Diff(ModuleDefinition slice, ModuleDefinition x64, ModuleDefinition a32, out int types, out int methods)
    {
        var t64 = All(x64.Types).ToDictionary(t => t.FullName, StringComparer.Ordinal);
        var t32 = All(a32.Types).ToDictionary(t => t.FullName, StringComparer.Ordinal);
        var findings = new List<Finding>();
        types = methods = 0;
        foreach (var st in All(slice.Types))
        {
            var name = Original(st);
            if (!t64.TryGetValue(name, out var tx)) continue; // csharpc's own (the bridge, hosted members, hoisted names)
            if (!t32.TryGetValue(name, out var ta)) { findings.Add(new("type only in the 64-bit CoreLib", name, "")); continue; }
            types++;
            if (InlineLength(tx) != InlineLength(ta))
                findings.Add(new("[InlineArray] length", name, $"64-bit {InlineLength(tx)}, 32-bit {InlineLength(ta)} of {tx.Fields.FirstOrDefault(f => !f.IsStatic)?.FieldType.FullName}"));
            if (tx.ClassSize != ta.ClassSize || tx.PackingSize != ta.PackingSize)
                findings.Add(new("class size or packing", name, $"64-bit {tx.ClassSize}/{tx.PackingSize}, 32-bit {ta.ClassSize}/{ta.PackingSize}"));
            foreach (var f in st.Fields)
            {
                var fx = tx.Fields.FirstOrDefault(x => x.Name == f.Name);
                if (fx is null) continue;
                var fa = ta.Fields.FirstOrDefault(x => x.Name == f.Name);
                var where = $"{name}::{f.Name}";
                if (fa is null) findings.Add(new("field only in the 64-bit CoreLib", where, fx.FieldType.FullName));
                else
                {
                    if (fx.FieldType.FullName != fa.FieldType.FullName) findings.Add(new("field type", where, $"64-bit {fx.FieldType.FullName}, 32-bit {fa.FieldType.FullName}"));
                    if (fx.Offset != fa.Offset) findings.Add(new("field offset", where, $"64-bit {fx.Offset}, 32-bit {fa.Offset}"));
                    if (fx.HasConstant && (!fa.HasConstant || !Equals(fx.Constant, fa.Constant))) findings.Add(new("constant", where, $"64-bit {fx.Constant}, 32-bit {(fa.HasConstant ? fa.Constant : "none")}"));
                    if (fx.InitialValue is { Length: > 0 } data && (fa.InitialValue is not { } other || !data.AsSpan().SequenceEqual(other)))
                        findings.Add(new("RVA data", where, $"64-bit {data.Length} B, 32-bit {fa.InitialValue?.Length ?? 0} B"));
                }
            }
            foreach (var sm in st.Methods)
                foreach (var m in tx.Methods.Where(m => m.Name == sm.Name && m.Parameters.Count == sm.Parameters.Count && m.GenericParameters.Count == sm.GenericParameters.Count))
                {
                    var ma = ta.Methods.FirstOrDefault(x => Signature(x) == Signature(m));
                    if (ma is null) { findings.Add(new("method only in the 64-bit CoreLib", $"{name}::{Signature(m)}", "")); continue; }
                    methods++;
                    var bx = Body(m);
                    var ba = Body(ma);
                    if (!bx.SequenceEqual(ba)) findings.Add(new("method body", $"{name}::{Signature(m)}", $"{bx.Count} instructions (64-bit), {ba.Count} (32-bit)"));
                }
        }
        return findings;
    }
}
