using System.Collections.Immutable;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Text;
using System.Text.RegularExpressions;
using Csharpc.Frontend.Il;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Csharpc.Frontend;

/// <summary>
/// [GeneratedRegex] in a program given as IL (`csharpc app.dll`). The SDK's generator already ran: each member's
/// body reads `Instance` of a generated Regex subclass whose matching code is built on RegexRunner internals,
/// which the corelib's Regex doesn't have. As for sources (GeneratedRegex.cs), csharpc makes the member a cached
/// instance of the corelib's interpreter built from the attribute — one per generated class, so members the SDK
/// generator made share an implementation (same pattern and options) still return the same instance.
/// </summary>
internal static class IlGeneratedRegex
{
    private const string HolderNamespace = "CsharpcGeneratedRegex";

    /// <summary>The program's [GeneratedRegex] methods (property getters included), by metadata token: the holder type's metadata name.</summary>
    private static Dictionary<int, string> s_holders = [];

    /// <summary>The program's assembly: tokens are per assembly, and every IL library has methods with the same ones.</summary>
    private static string? s_program;

    /// <summary>The holder whose Get() replaces <paramref name="method"/>'s IL body, if it is a [GeneratedRegex] member of the program.</summary>
    public static string? HolderFor(IMethodSymbol method) =>
        s_program is not null && method.OriginalDefinition.ContainingAssembly?.Identity.Name == s_program
        && method.OriginalDefinition.MetadataToken is var token and not 0 && s_holders.TryGetValue(token, out var holder) ? holder : null;

    /// <summary>The holders' source, or null when the program has no [GeneratedRegex] member csharpc can redirect.</summary>
    public static SyntaxTree? Synthesize(IlAssembly program, CSharpParseOptions options)
    {
        s_holders = [];
        s_program = program.Reader.GetString(program.Reader.GetAssemblyDefinition().Name);
        var reader = program.Reader;
        var members = new List<(MethodDefinitionHandle Method, CustomAttribute Attribute)>();
        foreach (var handle in reader.MethodDefinitions)
            if (Attribute(reader, reader.GetMethodDefinition(handle).GetCustomAttributes()) is { } attribute) members.Add((handle, attribute));
        foreach (var handle in reader.PropertyDefinitions)
        {
            var property = reader.GetPropertyDefinition(handle);
            if (Attribute(reader, property.GetCustomAttributes()) is { } attribute && property.GetAccessors().Getter is { IsNil: false } getter)
                members.Add((getter, attribute));
        }
        if (members.Count == 0) return null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> csharpc: the IL program's [GeneratedRegex] members as cached instances of the corelib's Regex interpreter.");
        sb.AppendLine($"namespace {HolderNamespace}");
        sb.AppendLine("{");
        var made = new Dictionary<int, string>();
        foreach (var (method, attribute) in members)
        {
            // csc's body for the generated member: `ldsfld <Generated>::Instance; ret`. Anything else is left alone
            // (its IL then reports what the corelib's Regex lacks).
            if (InstanceField(program, reader.GetMethodDefinition(method)) is not { } field || Arguments(reader, attribute) is not { } args) continue;
            var fieldToken = MetadataTokens.GetToken(field);
            if (!made.TryGetValue(fieldToken, out var holder))
            {
                holder = $"Holder_{MetadataTokens.GetRowNumber(field)}";
                made[fieldToken] = holder;
                sb.AppendLine($"    internal static class {holder}");
                sb.AppendLine("    {");
                sb.AppendLine("        private static readonly global::System.Text.RegularExpressions.Regex s_instance = (global::System.Text.RegularExpressions.Regex)(object)"
                    + $"global::CsharpcCoreLib.RegularExpressions.Regex.CreateForGeneratedRegex({Literal(args.Pattern)}, "
                    + $"(global::System.Text.RegularExpressions.RegexOptions)({args.Options}), {(args.MatchTimeout is { } t ? t.ToString() : "int.MinValue")}, {Literal(args.CultureName)});");
                sb.AppendLine("        internal static global::System.Text.RegularExpressions.Regex Get() => s_instance;");
                sb.AppendLine("    }");
            }
            s_holders[MetadataTokens.GetToken(method)] = HolderNamespace + "." + holder;
        }
        sb.AppendLine("}");
        return made.Count == 0 ? null : CSharpSyntaxTree.ParseText(sb.ToString(), options, path: "<csharpc-il-generated-regex>.g.cs");
    }

    private static CustomAttribute? Attribute(MetadataReader reader, CustomAttributeHandleCollection attributes)
    {
        foreach (var handle in attributes)
        {
            var attribute = reader.GetCustomAttribute(handle);
            var type = attribute.Constructor.Kind switch
            {
                HandleKind.MemberReference => reader.GetMemberReference((MemberReferenceHandle)attribute.Constructor).Parent,
                HandleKind.MethodDefinition => reader.GetMethodDefinition((MethodDefinitionHandle)attribute.Constructor).GetDeclaringType(),
                _ => default,
            };
            if (type.Kind == HandleKind.TypeReference && reader.GetTypeReference((TypeReferenceHandle)type) is var r
                && reader.StringComparer.Equals(r.Name, "GeneratedRegexAttribute") && reader.StringComparer.Equals(r.Namespace, "System.Text.RegularExpressions"))
                return attribute;
        }
        return null;
    }

    private static FieldDefinitionHandle? InstanceField(IlAssembly program, MethodDefinition method)
    {
        if (method.RelativeVirtualAddress == 0) return null;
        var il = program.Pe.GetMethodBody(method.RelativeVirtualAddress).GetILBytes();
        if (il is not [0x7E, _, _, _, _, 0x2A]) return null;
        var token = BitConverter.ToInt32(il, 1);
        return MetadataTokens.EntityHandle(token) is { Kind: HandleKind.FieldDefinition } handle ? (FieldDefinitionHandle)handle : null;
    }

    private sealed record RegexArguments(string Pattern, int Options, int? MatchTimeout, string CultureName);

    /// <summary>The attribute's constructor arguments, normalized as GeneratedRegexGenerator.Analyze does.</summary>
    private static RegexArguments? Arguments(MetadataReader reader, CustomAttribute attribute)
    {
        CustomAttributeValue<string> value;
        try { value = attribute.DecodeValue(new AttributeTypes()); }
        catch (Exception e) when (e is BadImageFormatException or InvalidOperationException) { return null; }
        var args = value.FixedArguments;
        if (args.Length is 0 or > 4 || args[0].Value is not string pattern) return null;
        var options = 0;
        int? matchTimeout = null;
        var cultureName = "";
        if (args.Length >= 2)
        {
            if (args[1].Value is not int o) return null;
            options = o;
            if (args.Length == 4) { matchTimeout = args[2].Value as int?; cultureName = args[3].Value as string; }
            else if (args.Length == 3)
            {
                if (args[2].Value is int timeout) matchTimeout = timeout;
                else cultureName = args[2].Value as string;
            }
        }
        if (cultureName is null) return null;
        // The culture only matters for case-insensitive patterns (option or inline (?i)).
        var ignoreCase = (options & (int)RegexOptions.IgnoreCase) != 0 || Regex.IsMatch(pattern, @"\(\?[imnsx-]*i");
        return new RegexArguments(pattern, options, matchTimeout, ignoreCase ? cultureName : "");
    }

    private static string Literal(string s) => SymbolDisplay.FormatLiteral(s, quote: true);

    /// <summary>Attribute argument types as names; enums (RegexOptions) decode as their underlying int.</summary>
    private sealed class AttributeTypes : ICustomAttributeTypeProvider<string>
    {
        public string GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode.ToString();
        public string GetSystemType() => "System.Type";
        public string GetSZArrayType(string elementType) => elementType + "[]";
        public string GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind) => reader.GetString(reader.GetTypeDefinition(handle).Name);
        public string GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind) => reader.GetString(reader.GetTypeReference(handle).Name);
        public string GetTypeFromSerializedName(string name) => name;
        public PrimitiveTypeCode GetUnderlyingEnumType(string type) => type == "RegexOptions"
            ? PrimitiveTypeCode.Int32
            : throw new InvalidOperationException($"enum '{type}' in a [GeneratedRegex] attribute");
        public bool IsSystemType(string type) => type == "System.Type";
    }
}
