// System.String and System.Char, implemented in C# (formerly src/runtime/strings.c).
//
// [ShadowInstance] statics take the receiver as their first parameter and implement the library
// instance method of the same name (CoreLib.MatchInstanceShadow); codegen null-checks the receiver,
// so these bodies may assume it is non-null. Semantics follow .NET with InvariantGlobalization:
// ordinal comparisons, invariant (ASCII + Latin-1) casing.
#nullable disable
using System;

namespace CsharpcCoreLib
{
    [ShadowMembers("System.Char")]
    internal static class CharOps
    {
        // Categories and case mappings come from .NET's own Unicode data (UnicodeData.g.cs, generated by
        // tools/unicode/GenUnicodeTables.cs), so every predicate matches .NET exactly.
        private static int Decode(ReadOnlySpan<byte> table, int index) =>
            ((table[index] - '0') << 12) | ((table[index + 1] - '0') << 6) | (table[index + 2] - '0');

        public static System.Globalization.UnicodeCategory GetUnicodeCategory(char c)
        {
            if (c < 256) return (System.Globalization.UnicodeCategory)(UnicodeData.Latin1Categories[c] - '0');
            // Binary search: last breakpoint whose start <= c. Each entry is 6 symbols: start, category.
            ReadOnlySpan<byte> table = UnicodeData.Categories;
            int lo = 0, hi = UnicodeData.CategoryCount - 1;
            while (lo < hi)
            {
                int mid = (lo + hi + 1) >> 1;
                if (Decode(table, mid * 6) <= c) lo = mid; else hi = mid - 1;
            }
            return (System.Globalization.UnicodeCategory)Decode(table, lo * 6 + 3);
        }

        private static int Cat(char c) => (int)GetUnicodeCategory(c);

        // UnicodeCategory values: 0 Lu, 1 Ll, 2 Lt, 3 Lm, 4 Lo, 5 Mn, 6 Mc, 7 Me, 8 Nd, 9 Nl, 10 No,
        // 11 Zs, 12 Zl, 13 Zp, 14 Cc, 15 Cf, 16 Cs, 17 Co, 18 Pc, 19 Pd, 20 Ps, 21 Pe, 22 Pi, 23 Pf,
        // 24 Po, 25 Sm, 26 Sc, 27 Sk, 28 So, 29 Cn
        public static bool IsLetter(char c) => c < 128 ? (uint)((c | 0x20) - 'a') <= 'z' - 'a' : Cat(c) <= 4;
        public static bool IsDigit(char c) => c < 128 ? (uint)(c - '0') <= 9 : Cat(c) == 8;
        public static bool IsLetterOrDigit(char c) { int k = Cat(c); return k <= 4 || k == 8; }
        public static bool IsNumber(char c) { int k = Cat(c); return k >= 8 && k <= 10; }
        public static bool IsUpper(char c) => c < 128 ? (uint)(c - 'A') <= 'Z' - 'A' : Cat(c) == 0;
        public static bool IsLower(char c) => c < 128 ? (uint)(c - 'a') <= 'z' - 'a' : Cat(c) == 1;
        public static bool IsPunctuation(char c) { int k = Cat(c); return k >= 18 && k <= 24; }
        public static bool IsSymbol(char c) { int k = Cat(c); return k >= 25 && k <= 28; }
        public static bool IsSeparator(char c) { int k = Cat(c); return k >= 11 && k <= 13; }
        public static bool IsControl(char c) => Cat(c) == 14;
        public static bool IsSurrogate(char c) => (uint)(c - 0xD800) <= 0x7FF;
        public static bool IsHighSurrogate(char c) => (uint)(c - 0xD800) <= 0x3FF;
        public static bool IsLowSurrogate(char c) => (uint)(c - 0xDC00) <= 0x3FF;
        public static bool IsAscii(char c) => c < 128;
        public static bool IsAsciiDigit(char c) => (uint)(c - '0') <= 9;
        public static bool IsAsciiLetter(char c) => (uint)((c | 0x20) - 'a') <= 'z' - 'a';
        public static bool IsAsciiLetterUpper(char c) => (uint)(c - 'A') <= 'Z' - 'A';
        public static bool IsAsciiLetterLower(char c) => (uint)(c - 'a') <= 'z' - 'a';
        public static bool IsAsciiLetterOrDigit(char c) => IsAsciiLetter(c) || IsAsciiDigit(c);
        public static bool IsAsciiHexDigit(char c) => IsAsciiDigit(c) || (uint)((c | 0x20) - 'a') <= 'f' - 'a';

        /// <summary>.NET: Latin-1 white space (tab..CR, space, U+0085, U+00A0), else categories Zs/Zl/Zp.</summary>
        public static bool IsWhiteSpace(char c)
        {
            if (c < 256) return c == ' ' || (uint)(c - '\t') <= '\r' - '\t' || c == '\u0085' || c == ' ';
            int k = Cat(c);
            return k >= 11 && k <= 13;
        }

        private static char MapCase(char c, ReadOnlySpan<byte> dense, ReadOnlySpan<byte> runs, int runCount)
        {
            if (c < UnicodeData.DenseCaseLimit) return (char)(c + Decode(dense, c * 3));
            for (int i = 0; i < runCount; i++)
            {
                int at = i * 12;
                int start = Decode(runs, at);
                if (c < start) break; // runs are sorted by start
                if (c <= Decode(runs, at + 3) && (c - start) % Decode(runs, at + 6) == 0)
                    return (char)(c + Decode(runs, at + 9));
            }
            return c;
        }

        public static char ToUpperInvariant(char c)
        {
            if (c < 128) return (uint)(c - 'a') <= 'z' - 'a' ? (char)(c - 32) : c;
            return MapCase(c, UnicodeData.UpperDense, UnicodeData.UpperRuns, UnicodeData.UpperRunCount);
        }

        public static char ToLowerInvariant(char c)
        {
            if (c < 128) return (uint)(c - 'A') <= 'Z' - 'A' ? (char)(c + 32) : c;
            return MapCase(c, UnicodeData.LowerDense, UnicodeData.LowerRuns, UnicodeData.LowerRunCount);
        }

        // csharpc programs run in the invariant culture.
        public static char ToUpper(char c) => ToUpperInvariant(c);
        public static char ToLower(char c) => ToLowerInvariant(c);
    }

    [ShadowMembers("System.String")]
    internal static class StringOps
    {
        /// <summary>Length sums are computed in 64 bits so they can't wrap; too long is OutOfMemoryException, as in .NET.</summary>
        private static string AllocateString(long length)
        {
            if (length > int.MaxValue) throw new OutOfMemoryException();
            return CoreIntrinsics.FastAllocateString((int)length);
        }

        private static string Copy(ReadOnlySpan<char> chars)
        {
            string result = CoreIntrinsics.FastAllocateString(chars.Length);
            chars.CopyTo(CoreIntrinsics.StringChars(result));
            return result;
        }

        // ---- slicing ----------------------------------------------------------------------------
        [ShadowInstance]
        public static string Substring(string s, int startIndex) => Substring(s, startIndex, s.Length - startIndex);

        [ShadowInstance]
        public static string Substring(string s, int startIndex, int length)
        {
            ThrowHelper.IfNegative(startIndex, "startIndex");
            if (startIndex > s.Length)
                throw new ArgumentOutOfRangeException("startIndex", "startIndex cannot be larger than length of string.");
            ThrowHelper.IfNegative(length, "length");
            if (startIndex > s.Length - length)
                throw new ArgumentOutOfRangeException("length", "Index and length must refer to a location within the string.");
            if (length == s.Length) return s;
            return Copy(s.AsSpan(startIndex, length));
        }

        [ShadowInstance]
        public static string Insert(string s, int startIndex, string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            ThrowHelper.IfGreaterThan((uint)startIndex, (uint)s.Length, "startIndex");
            string result = AllocateString((long)s.Length + value.Length);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            s.AsSpan(0, startIndex).CopyTo(dst);
            value.AsSpan().CopyTo(dst.Slice(startIndex));
            s.AsSpan(startIndex).CopyTo(dst.Slice(startIndex + value.Length));
            return result;
        }

        [ShadowInstance]
        public static string Remove(string s, int startIndex)
        {
            if (startIndex < 0) throw new ArgumentOutOfRangeException("startIndex", "StartIndex cannot be less than zero.");
            if (startIndex > s.Length) throw new ArgumentOutOfRangeException("startIndex", "startIndex cannot be larger than length of string.");
            return startIndex == s.Length ? s : Copy(s.AsSpan(0, startIndex));
        }

        [ShadowInstance]
        public static string Remove(string s, int startIndex, int count)
        {
            ThrowHelper.IfNegative(startIndex, "startIndex");
            ThrowHelper.IfNegative(count, "count");
            ThrowHelper.IfGreaterThan(count, s.Length - startIndex, "count");
            if (count == 0) return s;
            string result = CoreIntrinsics.FastAllocateString(s.Length - count);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            s.AsSpan(0, startIndex).CopyTo(dst);
            s.AsSpan(startIndex + count).CopyTo(dst.Slice(startIndex));
            return result;
        }

        // ---- searching --------------------------------------------------------------------------
        [ShadowInstance] public static int IndexOf(string s, char value) => IndexOf(s, value, 0);

        [ShadowInstance]
        public static int IndexOf(string s, char value, int startIndex)
        {
            if ((uint)startIndex > (uint)s.Length) ThrowHelper.IndexMustBeLessOrEqual("startIndex");
            ReadOnlySpan<char> chars = s.AsSpan();
            for (int i = startIndex; i < chars.Length; i++)
                if (chars[i] == value) return i;
            return -1;
        }

        [ShadowInstance]
        public static int LastIndexOf(string s, char value)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            for (int i = chars.Length - 1; i >= 0; i--)
                if (chars[i] == value) return i;
            return -1;
        }

        [ShadowInstance] public static int IndexOf(string s, string value) => IndexOf(s, value, 0);

        [ShadowInstance]
        public static int IndexOf(string s, string value, int startIndex)
        {
            if (value == null) throw new ArgumentNullException("value");
            if ((uint)startIndex > (uint)s.Length) ThrowHelper.IndexMustBeLessOrEqual("startIndex");
            return IndexOfOrdinal(s.AsSpan(), value.AsSpan(), startIndex);
        }

        /// <summary>
        /// Scan for the first char, then compare the rest. Pointers rather than span indexing: the
        /// `i <= last` bound already covers every access, but LLVM can't prove it and keeps a range
        /// check per char.
        /// </summary>
        internal static unsafe int IndexOfOrdinal(ReadOnlySpan<char> s, ReadOnlySpan<char> value, int startIndex)
        {
            if (value.Length == 0) return startIndex;
            int last = s.Length - value.Length;
            if ((uint)startIndex > (uint)s.Length) return -1;
            fixed (char* sp = s, vp = value)
            {
                // nint indices: C# int arithmetic wraps (no `nsw`), so an int counter would be
                // sign-extended on every access instead of becoming a 64-bit induction variable.
                char first = vp[0];
                nint rest = value.Length - 1;
                for (nint i = startIndex; i <= last; i++)
                {
                    if (sp[i] != first) continue;
                    nint k = 0;
                    while (k < rest && sp[i + 1 + k] == vp[1 + k]) k++;
                    if (k == rest) return (int)i;
                }
            }
            return -1;
        }

        [ShadowInstance] public static bool Contains(string s, string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            return IndexOfOrdinal(s.AsSpan(), value.AsSpan(), 0) >= 0;
        }

        [ShadowInstance] public static bool Contains(string s, char value) => IndexOf(s, value, 0) >= 0;

        [ShadowInstance]
        public static bool StartsWith(string s, string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            return value.Length <= s.Length && EqualsOrdinal(s.AsSpan(0, value.Length), value.AsSpan());
        }

        [ShadowInstance]
        public static bool EndsWith(string s, string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            return value.Length <= s.Length && EqualsOrdinal(s.AsSpan(s.Length - value.Length), value.AsSpan());
        }

        internal static bool EqualsOrdinal(ReadOnlySpan<char> a, ReadOnlySpan<char> b)
        {
            if (a.Length != b.Length) return false;
            for (int i = 0; i < a.Length; i++)
                if (a[i] != b[i]) return false;
            return true;
        }

        private static bool AnyOf(char c, char[] set)
        {
            for (int i = 0; i < set.Length; i++)
                if (set[i] == c) return true;
            return false;
        }

        [ShadowInstance] public static int IndexOfAny(string s, char[] anyOf) => IndexOfAny(s, anyOf, 0);

        [ShadowInstance]
        public static int IndexOfAny(string s, char[] anyOf, int startIndex)
        {
            if (anyOf == null) throw new ArgumentNullException("anyOf");
            if ((uint)startIndex > (uint)s.Length) ThrowHelper.IndexMustBeLessOrEqual("startIndex");
            ReadOnlySpan<char> chars = s.AsSpan();
            for (int i = startIndex; i < chars.Length; i++)
                if (AnyOf(chars[i], anyOf)) return i;
            return -1;
        }

        [ShadowInstance]
        public static int LastIndexOfAny(string s, char[] anyOf)
        {
            if (anyOf == null) throw new ArgumentNullException("anyOf");
            ReadOnlySpan<char> chars = s.AsSpan();
            for (int i = chars.Length - 1; i >= 0; i--)
                if (AnyOf(chars[i], anyOf)) return i;
            return -1;
        }

        // ---- case mapping -----------------------------------------------------------------------
        [ShadowInstance]
        public static string ToUpper(string s)
        {
            ReadOnlySpan<char> src = s.AsSpan();
            string result = CoreIntrinsics.FastAllocateString(src.Length);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            for (int i = 0; i < src.Length; i++) dst[i] = CharOps.ToUpper(src[i]);
            return result;
        }

        [ShadowInstance]
        public static string ToLower(string s)
        {
            ReadOnlySpan<char> src = s.AsSpan();
            string result = CoreIntrinsics.FastAllocateString(src.Length);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            for (int i = 0; i < src.Length; i++) dst[i] = CharOps.ToLower(src[i]);
            return result;
        }

        [ShadowInstance] public static string ToUpperInvariant(string s) => ToUpper(s);
        [ShadowInstance] public static string ToLowerInvariant(string s) => ToLower(s);

        // ---- trimming ---------------------------------------------------------------------------
        private const int TrimHead = 1, TrimTail = 2, TrimBoth = 3;

        private static string TrimWhiteSpace(string s, int mode)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && CharOps.IsWhiteSpace(chars[start])) start++;
            if ((mode & TrimTail) != 0) while (end > start && CharOps.IsWhiteSpace(chars[end - 1])) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        private static string TrimChar(string s, char c, int mode)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && chars[start] == c) start++;
            if ((mode & TrimTail) != 0) while (end > start && chars[end - 1] == c) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        /// <summary>A null or empty set means white space, as in .NET.</summary>
        private static string TrimSet(string s, char[] set, int mode)
        {
            if (set == null || set.Length == 0) return TrimWhiteSpace(s, mode);
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && AnyOf(chars[start], set)) start++;
            if ((mode & TrimTail) != 0) while (end > start && AnyOf(chars[end - 1], set)) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        /// <summary>.NET 9+ params ReadOnlySpan&lt;char&gt; overloads; an empty set means white space.</summary>
        private static string TrimSpanSet(string s, ReadOnlySpan<char> set, int mode)
        {
            if (set.Length == 0) return TrimWhiteSpace(s, mode);
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && set.IndexOf(chars[start]) >= 0) start++;
            if ((mode & TrimTail) != 0) while (end > start && set.IndexOf(chars[end - 1]) >= 0) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        [ShadowInstance] public static string Trim(string s, ReadOnlySpan<char> trimChars) => TrimSpanSet(s, trimChars, TrimBoth);
        [ShadowInstance] public static string TrimStart(string s, ReadOnlySpan<char> trimChars) => TrimSpanSet(s, trimChars, TrimHead);
        [ShadowInstance] public static string TrimEnd(string s, ReadOnlySpan<char> trimChars) => TrimSpanSet(s, trimChars, TrimTail);

        [ShadowInstance] public static string Trim(string s) => TrimWhiteSpace(s, TrimBoth);
        [ShadowInstance] public static string TrimStart(string s) => TrimWhiteSpace(s, TrimHead);
        [ShadowInstance] public static string TrimEnd(string s) => TrimWhiteSpace(s, TrimTail);
        [ShadowInstance] public static string Trim(string s, char trimChar) => TrimChar(s, trimChar, TrimBoth);
        [ShadowInstance] public static string TrimStart(string s, char trimChar) => TrimChar(s, trimChar, TrimHead);
        [ShadowInstance] public static string TrimEnd(string s, char trimChar) => TrimChar(s, trimChar, TrimTail);
        [ShadowInstance] public static string Trim(string s, char[] trimChars) => TrimSet(s, trimChars, TrimBoth);
        [ShadowInstance] public static string TrimStart(string s, char[] trimChars) => TrimSet(s, trimChars, TrimHead);
        [ShadowInstance] public static string TrimEnd(string s, char[] trimChars) => TrimSet(s, trimChars, TrimTail);

        // ---- replacing / padding ----------------------------------------------------------------
        [ShadowInstance]
        public static string Replace(string s, char oldChar, char newChar)
        {
            int first = IndexOf(s, oldChar, 0);
            if (first < 0) return s;
            ReadOnlySpan<char> src = s.AsSpan();
            string result = CoreIntrinsics.FastAllocateString(src.Length);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            src.Slice(0, first).CopyTo(dst);
            for (int i = first; i < src.Length; i++) dst[i] = src[i] == oldChar ? newChar : src[i];
            return result;
        }

        [ShadowInstance]
        public static string Replace(string s, string oldValue, string newValue)
        {
            if (oldValue == null) throw new ArgumentNullException("oldValue");
            if (oldValue.Length == 0) throw new ArgumentException("The value cannot be an empty string.", "oldValue");
            ReadOnlySpan<char> src = s.AsSpan(), from = oldValue.AsSpan();
            ReadOnlySpan<char> to = newValue == null ? ReadOnlySpan<char>.Empty : newValue.AsSpan();
            int count = 0;
            for (int i = IndexOfOrdinal(src, from, 0); i >= 0; i = IndexOfOrdinal(src, from, i + from.Length)) count++;
            if (count == 0) return s;
            string result = AllocateString(src.Length + (long)count * (to.Length - from.Length));
            Span<char> dst = CoreIntrinsics.StringChars(result);
            int read = 0, write = 0;
            for (int i = IndexOfOrdinal(src, from, 0); i >= 0; i = IndexOfOrdinal(src, from, read))
            {
                src.Slice(read, i - read).CopyTo(dst.Slice(write));
                write += i - read;
                to.CopyTo(dst.Slice(write));
                write += to.Length;
                read = i + from.Length;
            }
            src.Slice(read).CopyTo(dst.Slice(write));
            return result;
        }

        private static string Pad(string s, int totalWidth, char paddingChar, bool left)
        {
            ThrowHelper.IfNegative(totalWidth, "totalWidth");
            if (totalWidth <= s.Length) return s;
            string result = CoreIntrinsics.FastAllocateString(totalWidth);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            int pad = totalWidth - s.Length;
            if (left)
            {
                dst.Slice(0, pad).Fill(paddingChar);
                s.AsSpan().CopyTo(dst.Slice(pad));
            }
            else
            {
                s.AsSpan().CopyTo(dst);
                dst.Slice(s.Length).Fill(paddingChar);
            }
            return result;
        }

        [ShadowInstance] public static string PadLeft(string s, int totalWidth) => Pad(s, totalWidth, ' ', true);
        [ShadowInstance] public static string PadRight(string s, int totalWidth) => Pad(s, totalWidth, ' ', false);
        [ShadowInstance] public static string PadLeft(string s, int totalWidth, char paddingChar) => Pad(s, totalWidth, paddingChar, true);
        [ShadowInstance] public static string PadRight(string s, int totalWidth, char paddingChar) => Pad(s, totalWidth, paddingChar, false);

        // ---- splitting / conversion -------------------------------------------------------------
        [ShadowInstance]
        public static string[] Split(string s, char separator, StringSplitOptions options)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            bool removeEmpty = (options & StringSplitOptions.RemoveEmptyEntries) != 0;
            bool trim = (options & StringSplitOptions.TrimEntries) != 0;
            int pieces = 1;
            for (int i = 0; i < chars.Length; i++) if (chars[i] == separator) pieces++;
            string[] parts = new string[pieces];
            int n = 0, start = 0;
            for (int i = 0; i <= chars.Length; i++)
            {
                if (i < chars.Length && chars[i] != separator) continue;
                int a = start, b = i;
                if (trim)
                {
                    while (a < b && CharOps.IsWhiteSpace(chars[a])) a++;
                    while (b > a && CharOps.IsWhiteSpace(chars[b - 1])) b--;
                }
                if (!(removeEmpty && a == b)) parts[n++] = b - a == chars.Length ? s : Copy(chars.Slice(a, b - a));
                start = i + 1;
            }
            if (n == parts.Length) return parts;
            string[] result = new string[n];
            Array.Copy(parts, result, n);
            return result;
        }

        public static string Join(string separator, string[] value)
        {
            if (value == null) throw new ArgumentNullException("value");
            int separatorLength = separator == null ? 0 : separator.Length;
            long total = 0;
            for (int i = 0; i < value.Length; i++) total += (value[i] == null ? 0 : value[i].Length) + (i > 0 ? separatorLength : 0);
            string result = AllocateString(total);
            Span<char> dst = CoreIntrinsics.StringChars(result);
            int at = 0;
            for (int i = 0; i < value.Length; i++)
            {
                if (i > 0 && separatorLength > 0) { separator.AsSpan().CopyTo(dst.Slice(at)); at += separatorLength; }
                string item = value[i];
                if (item != null) { item.AsSpan().CopyTo(dst.Slice(at)); at += item.Length; }
            }
            return result;
        }

        public static int CompareOrdinal(string strA, string strB)
        {
            if ((object)strA == strB) return 0;
            if (strA == null) return -1;
            if (strB == null) return 1;
            ReadOnlySpan<char> a = strA.AsSpan(), b = strB.AsSpan();
            int n = a.Length < b.Length ? a.Length : b.Length;
            for (int i = 0; i < n; i++)
                if (a[i] != b[i]) return a[i] - b[i];
            return a.Length - b.Length;
        }

        /// <summary>new string(c, count) — called by codegen for the string constructor.</summary>
        internal static string CreateRepeated(char c, int count)
        {
            ThrowHelper.IfNegative(count, "count");
            string result = CoreIntrinsics.FastAllocateString(count);
            CoreIntrinsics.StringChars(result).Fill(c);
            return result;
        }

        /// <summary>new string(char[]) — null gives the empty string.</summary>
        internal static string CreateFromChars(char[] value) => value == null ? "" : Copy(value);

        /// <summary>s[start..end] / list-pattern slices — codegen has already validated the range.</summary>
        internal static string Slice(string s, int startIndex, int length) => Substring(s, startIndex, length);

        [ShadowInstance]
        public static char[] ToCharArray(string s)
        {
            char[] result = new char[s.Length];
            s.AsSpan().CopyTo(result);
            return result;
        }
    }
