        // ---- trimming ---------------------------------------------------------------------------
        private const int TrimHead = 1, TrimTail = 2, TrimBoth = 3;

        private static string TrimWhiteSpace(string s, int mode)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && CharOps.IsWhiteSpace(chars[start])) start++;
            if ((mode & TrimTail) != 0) while (end > start && CharOps.IsWhiteSpace(chars[end - 1])) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        private static string TrimChar(string s, char c, int mode)
        {
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && chars[start] == c) start++;
            if ((mode & TrimTail) != 0) while (end > start && chars[end - 1] == c) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        /// <summary>A null or empty set means white space, as in .NET.</summary>
        private static string TrimSet(string s, char[] set, int mode)
        {
            if (set == null || set.Length == 0) return TrimWhiteSpace(s, mode);
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && AnyOf(chars[start], set)) start++;
            if ((mode & TrimTail) != 0) while (end > start && AnyOf(chars[end - 1], set)) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

        /// <summary>.NET 9+ params ReadOnlySpan&lt;char&gt; overloads; an empty set means white space.</summary>
        private static string TrimSpanSet(string s, ReadOnlySpan<char> set, int mode)
        {
            if (set.Length == 0) return TrimWhiteSpace(s, mode);
            ReadOnlySpan<char> chars = s.AsSpan();
            int start = 0, end = chars.Length;
            if ((mode & TrimHead) != 0) while (start < end && set.IndexOf(chars[start]) >= 0) start++;
            if ((mode & TrimTail) != 0) while (end > start && set.IndexOf(chars[end - 1]) >= 0) end--;
            return start == 0 && end == chars.Length ? s : Copy(chars.Slice(start, end - start));
        }

